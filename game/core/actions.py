# ================================================================ 卡片结构


@dataclass(frozen=True)
class ActionCard:
    """一张行动卡。字段顺序与 ``docs/CONTENT_SPEC.md`` 第 5 节完全一致。"""

    id: str
    name: str                       # <=8 个汉字，卡片标题
    text: str                       # 1-2 句，写清“你具体干了什么”，<=60 字
    rarity: str
    sem_lo: int                     # 最早可用学期
    sem_hi: int                     # 最晚可用学期
    effects: dict[str, int]         # 属性收益（权重）
    resources: dict[str, int]       # {"fatigue": +2, "money": -3}，可空
    flags: tuple[str, ...]          # 触发的 flag，可空
    hobby: tuple[str, int] | None   # (爱好 id, 经验)，可空
    majors: tuple[str, ...]         # () = 通用卡；否则只有这些专业可见
    is_flex: bool                   # True = 相邻专业也能看见
    tags: tuple[str, ...]
    track: str                      # 归属赛道，"" = 通用
    attribute_gate: dict[str, int]  # 前置门槛，可空
    start_affinity: tuple[str, ...] # 只给这些起步线额外露出，() = 所有人
    contest_id: str                 # 竞赛关联（一般 ""）
    contest_tier: str               # 竞赛阶梯（一般 ""）
    note: str                       # 给复盘用的一句旁白，可空


def _c(
    cid: str,
    name: str,
    rarity: str,
    sem_lo: int,
    sem_hi: int,
    text: str,
    effects: dict[str, int],
    *,
    resources: dict[str, int] | None = None,
    flags: tuple[str, ...] = (),
    hobby: tuple[str, int] | None = None,
    majors: tuple[str, ...] = (),
    is_flex: bool = False,
    tags: tuple[str, ...] = (),
    track: str = "",
    gate: dict[str, int] | None = None,
    affinity: tuple[str, ...] = (),
    contest_id: str = "",
    contest_tier: str = "",
    note: str = "",
) -> ActionCard:
    """构造一张行动卡。省掉一堆重复的空字段，内容本身才是重点。"""
    return ActionCard(
        id=cid,
        name=name,
        text=text,
        rarity=rarity,
        sem_lo=sem_lo,
        sem_hi=sem_hi,
        effects=dict(effects),
        resources=dict(resources or {}),
        flags=tuple(flags),
        hobby=hobby,
        majors=tuple(majors),
        is_flex=is_flex,
        tags=tuple(tags),
        track=track,
        attribute_gate=dict(gate or {}),
        start_affinity=tuple(affinity),
        contest_id=contest_id,
        contest_tier=contest_tier,
        note=note,
    )


