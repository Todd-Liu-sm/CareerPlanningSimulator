def _build_contest_cards() -> tuple[ActionCard, ...]:
    """每个竞赛的每一阶生成一张行动卡。

    数量与 ``contests.STAGE_CARDS`` 里的总阶数完全一致。
    竞赛卡自身不带属性收益 —— 收益由 ``effects.py`` 按
    ``CONTEST_TIER_EFFECT`` × 竞赛 strengths 结算。
    """
    cards: list[ActionCard] = []
    seen: set[str] = set()
    for contest in K.CONTEST_LIST:
        for tier in contest.tiers:
            if tier not in C.CONTEST_TIERS:
                continue
            card_id = _contest_stage_id(contest.id, tier)
            if card_id in seen:
                continue
            seen.add(card_id)
            cards.append(
                ActionCard(
                    id=card_id,
                    name=f"{contest.name}・{C.CONTEST_TIER_NAMES[tier]}",
                    text=_STAGE_TEXT[tier],
                    rarity=_TIER_RARITY[tier],
                    sem_lo=C.CONTEST_TIER_EARLIEST[tier],
                    sem_hi=C.TOTAL_SEMESTERS,
                    effects={},
                    resources={},
                    flags=(),
                    hobby=None,
                    majors=tuple(contest.majors),
                    is_flex=contest.is_flex,
                    tags=("contest", "portfolio"),
                    track="",
                    attribute_gate={},
                    start_affinity=(),
                    contest_id=contest.id,
                    contest_tier=tier,
                    note=_STAGE_NOTE[tier],
                )
            )
    return tuple(cards)


CONTEST_CARDS: tuple[ActionCard, ...] = _build_contest_cards()


# ================================================================ 汇总与查询

ALL_CARDS: tuple[ActionCard, ...] = GENERAL_CARDS + MAJOR_CARDS + CONTEST_CARDS

CARDS: dict[str, ActionCard] = {card.id: card for card in ALL_CARDS}


def get(card_id: str) -> ActionCard:
    """按 id 取卡；不存在直接 KeyError，方便早发现拼写错误。"""
    return CARDS[card_id]


# 竞赛卡标了 is_flex 时，哪些专业看得见由 contests.for_major 说了算 ——
# 邻接表只维护在 contests.py 一份，这里不重复定义，避免两边跑偏。
_FLEX_CACHE: dict[str, tuple[str, ...]] = {}


def _visible_majors(card: ActionCard) -> tuple[str, ...]:
    """这张卡实际能被哪些专业看见（竞赛卡展开 is_flex）。"""
    if not card.majors:
        return M.all_ids()
    if not card.is_flex or not card.contest_id:
        return card.majors
    cached = _FLEX_CACHE.get(card.contest_id)
    if cached is None:
        cached = tuple(
            major_id
            for major_id in M.all_ids()
            if any(c.id == card.contest_id for c in K.for_major(major_id))
        )
        _FLEX_CACHE[card.contest_id] = cached
    return cached or card.majors


def for_major(major_id: str) -> list[ActionCard]:
    """某个专业能看见的全部卡片（通用卡 + 本专业专属卡）。"""
    return [card for card in ALL_CARDS if major_id in _visible_majors(card)]


def cards_for_semester(sem: int, major_id: str) -> list[ActionCard]:
    """某个专业在某学期能用的卡片。时间窗是闭区间 [sem_lo, sem_hi]。"""
    return [
        card
        for card in ALL_CARDS
        if card.sem_lo <= sem <= card.sem_hi and major_id in _visible_majors(card)
    ]


def card_is_contest(card: ActionCard) -> bool:
    """是不是竞赛阶梯卡。"""
    return bool(card.contest_id and card.contest_tier)


def contest_cards() -> list[ActionCard]:
    """全部竞赛阶梯卡。"""
    return [card for card in ALL_CARDS if card_is_contest(card)]


def rest_cards() -> list[ActionCard]:
    """保底休息卡：safe 品质且带 rest / sport tag。"""
    return [
        card
        for card in ALL_CARDS
        if card.rarity == "safe" and any(tag in C.REST_TAGS for tag in card.tags)
    ]


def major_cards(major_id: str) -> list[ActionCard]:
    """某个专业真正专属的卡（不含通用卡与竞赛卡）。"""
    return [
        card
        for card in MAJOR_CARDS
        if major_id in card.majors and not card.is_flex and not card.contest_id
    ]


def semester_coverage(major_id: str) -> dict[int, int]:
    """某个专业每个学期各有多少张专属可用卡（自检用）。"""
    return {
        sem: len(
            [
                card
                for card in major_cards(major_id)
                if card.sem_lo <= sem <= card.sem_hi
            ]
        )
        for sem in range(1, C.TOTAL_SEMESTERS + 1)
    }
