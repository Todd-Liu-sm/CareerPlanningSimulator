def _contest_stage_id(contest_id: str, tier: str) -> str:
    """取这一阶的卡片 id：优先用 contests 里排好的 STAGE_CARDS。"""
    table = K.STAGE_CARDS.get(contest_id) or {}
    card_id = table.get(tier)
    if card_id:
        return card_id
    return K.stage_card_id(contest_id, tier)


